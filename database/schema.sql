CREATE DATABASE IF NOT EXISTS kku_market CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kku_market;
CREATE TABLE IF NOT EXISTS users (
 firebase_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 email VARCHAR(320) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 price DECIMAL(10,2) NOT NULL,
 image_url VARCHAR(1024) DEFAULT NULL,
 image_public_id VARCHAR(255) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_posts_owner(owner_uid)
);
CREATE TABLE IF NOT EXISTS email_outbox (
 code VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 owner_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 post_id INT UNSIGNED NOT NULL,
 recipient VARCHAR(320) NOT NULL,
 subject VARCHAR(255) NOT NULL,
 body TEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 provider_id VARCHAR(255) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_mail_owner(owner_uid),
 INDEX idx_mail_status(status)
);
