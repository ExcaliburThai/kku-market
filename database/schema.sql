CREATE DATABASE IF NOT EXISTS kku_market CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kku_market;
CREATE TABLE IF NOT EXISTS users (
 firebase_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 email VARCHAR(320) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 price DECIMAL(10,2) NOT NULL,
 image_path VARCHAR(512) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_uid) REFERENCES users(firebase_uid),
 INDEX(owner_uid),
 CHECK (price >= 0)
);
